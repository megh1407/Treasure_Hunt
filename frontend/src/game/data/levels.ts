import type { Level } from "../types";
import { GAME_CONFIG } from "../config";

const { penalties } = GAME_CONFIG;

function scaffold(
  id: number,
  name: string,
  building: Level["building"],
  room: string,
  destination: string,
  type: Level["challenge"]["type"],
): Level {
  return {
    id,
    name,
    building,
    room,
    objective: "Follow the unlocked trace to locate the target.",
    playable: false,
    clue: {
      id: `clue-${id}`,
      levelId: id,
      text: "This trace is still encrypted.",
      destination,
      building,
      room,
      objectId: `${building}_target`,
      requiredItem: null,
      nextLevel: id < 10 ? id + 1 : null,
    },
    challenge: {
      id: `ch-${id}`,
      levelId: id,
      type,
      question: "Locked until this level is deployed.",
      answer: "",
      penaltySeconds: penalties.wrongAnswer,
      hints: [],
      active: false,
    },
    objects: [],
  };
}

